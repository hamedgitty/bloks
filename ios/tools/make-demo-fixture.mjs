#!/usr/bin/env node
// Builds the sample workspace the iOS app shows when it has no Mac to talk
// to.
//
//   node ios/tools/make-demo-fixture.mjs
//
// Why this exists: App Review has no Mac running Bloks. A reviewer opens
// the app, sees "Bloks is not reachable", and rejects it under guideline
// 2.1 as incomplete. They are not wrong to: from where they are sitting the
// app does nothing. The sample gives them the actual product in ten
// seconds, and gives anyone who downloads before installing the Mac app
// something better than an error.
//
// It is generated from scripts/seed-demo.mjs rather than hand-written, for
// the same reason the README screenshots are: a hand-made sample drifts
// from the real thing and nobody notices until it is embarrassing.
//
// Three things are added that the seed does not produce: an OPEN approval
// card, a workflow gate, and an answer that is not a paragraph. Answering
// something is the whole reason this app exists, so the sample has to
// contain one of each or it demonstrates the wrong product.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const out = join(repo, "ios", "Bloks", "Resources", "demo-workspace.json");

const home = mkdtempSync(join(tmpdir(), "bloks-demo-fixture-"));
try {
  execFileSync("node", [join(repo, "scripts", "seed-demo.mjs"), home], { stdio: "pipe" });
  const dir = join(home, ".bloks");

  const read = (name) => JSON.parse(readFileSync(join(dir, name), "utf8"));
  const transcript = (id) => {
    const file = readdirSync(dir).find((f) => f === `messages-${id}.json`);
    return file ? JSON.parse(readFileSync(join(dir, file), "utf8")) : [];
  };

  const bots = read("bots.json").map((bot) => ({ ...bot, messages: transcript(bot.threadId) }));
  const rooms = read("bloks.json").map((room) => ({ ...room, messages: transcript(room.id) }));

  // The approval goes on the most senior agent, because that is who would
  // realistically be doing something that needs a yes.
  const lead =
    bots.find((b) => (b.seniority ?? 1) >= 4) ?? bots[0];
  if (!lead) throw new Error("the seed produced no agents");

  const at = Math.max(...lead.messages.map((m) => m.at ?? 0), 0) + 60_000;
  lead.messages.push({
    id: "demo-ask",
    role: "bot",
    kind: "options",
    at,
    card: {
      title: "Approval needed",
      subtitle: "/bin/zsh -lc 'curl -sS https://api.github.com/repos/hamedgitty/bloks/releases'",
      options: ["Allow", "Deny"],
      // A requestId is what makes this render as a live approval rather
      // than a settled question. In the sample nothing is really blocked,
      // but the card has to look like the real one.
      requestId: "demo-request",
    },
  });
  lead.unread = true;

  // A workflow gate, which is not an approval however similar it looks: a
  // run is parked on it rather than a turn, it has two answers and no
  // third, and answering it resumes the run.
  lead.messages.push({
    id: "demo-gate",
    role: "bot",
    kind: "options",
    at: at + 60_000,
    card: {
      title: "Send the launch note to the list?",
      subtitle: "Launch checklist is waiting on this. It stops if nobody answers in about 2 hours.",
      options: ["Approve", "Decline"],
      runId: "demo-run",
    },
  });

  // An answer that is not prose. The analyst is the one who would have
  // numbers, and a chart in the transcript is the fastest way to show
  // that an answer here is real interface rather than markdown.
  const analyst = bots.find((b) => /analyst|research/i.test(b.title ?? b.name ?? "")) ?? bots[bots.length - 1];
  if (analyst) {
    const after = Math.max(...analyst.messages.map((m) => m.at ?? 0), 0) + 60_000;
    analyst.messages.push({
      id: "demo-component",
      role: "bot",
      kind: "component",
      at: after,
      component: {
        kind: "chart",
        title: "Where last month's signups came from",
        note: "Counted once per person, on first touch.",
        bars: [
          { label: "Search", value: 1840 },
          { label: "Newsletter", value: 1120 },
          { label: "Word of mouth", value: 760 },
          { label: "Paid", value: 240 },
        ],
      },
    });
  }

  const fixture = {
    note: "Sample workspace. Generated by ios/tools/make-demo-fixture.mjs from scripts/seed-demo.mjs. Not real data.",
    bots,
    rooms,
  };
  writeFileSync(out, JSON.stringify(fixture, null, 2));
  console.log(
    `wrote ${out}\n  ${bots.length} agents, ${rooms.length} room(s), 1 open approval, 1 workflow gate, 1 component`,
  );
} finally {
  rmSync(home, { recursive: true, force: true });
}
